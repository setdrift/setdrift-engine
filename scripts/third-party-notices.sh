#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES: the license, NOTICE and PATENTS files of every
# module compiled into the setdrift binary, for every platform we release.
#
# Why: Apache-2.0 (section 4) requires a binary to carry its dependencies'
# NOTICE files, and MIT, BSD and ISC require their license text. The source
# repo doesn't contain dependency code, but release archives do.
#
# Why this way: `go list` already knows exactly which modules each build
# links, and their files are in the module cache that go.sum verified, so no
# extra tool is needed. Modules differ by OS (cobra uses mousetrap only on
# Windows), so the list is the union over the release platforms.
# Output depends only on go.sum, so CI can check it is current
# (make notices && git diff --exit-code).
set -euo pipefail

cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES
platforms="linux/amd64 linux/arm64 darwin/amd64 darwin/arm64 windows/amd64 windows/arm64"
self=$(go list -m)

# module|version|dir for each dependency module, across all platforms
modules=$(
  for p in $platforms; do
    GOOS=${p%/*} GOARCH=${p#*/} CGO_ENABLED=0 go list -deps \
      -f '{{with .Module}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}' ./cmd/setdrift
  done | grep -v "^$self|" | sort -u
)

# checksums of the texts printed so far (bash 3 on macOS has no maps)
seen=$(mktemp)
trap 'rm -f "$seen"' EXIT

{
  echo "Third-party software in the setdrift binary"
  echo
  echo "The setdrift binary includes the modules below. Each is listed with its"
  echo "license and, where it has them, its NOTICE and PATENTS files, unchanged."
  echo "Generated by scripts/third-party-notices.sh (make notices); do not edit."
  while IFS='|' read -r path version dir; do
    files=$(cd "$dir" && ls | grep -iE '^(licen[cs]e|copying|notice|patents)' | sort || true)
    if [ -z "$files" ]; then
      echo "error: no license file in $path $version" >&2
      exit 1
    fi
    printf '\n\n%s\n%s %s\n%s\n' "================================================================================" "$path" "$version" "================================================================================"
    for f in $files; do
      # A text identical to one printed earlier (most Apache-2.0 copies) is
      # referenced rather than repeated, which keeps the file readable.
      sum=$(shasum -a 256 "$dir/$f" | cut -d' ' -f1)
      first=$(grep "^$sum " "$seen" | cut -d' ' -f2- || true)
      if [ -n "$first" ]; then
        printf '\n--- %s: identical to %s above ---\n' "$f" "$first"
      else
        echo "$sum $path $f" >>"$seen"
        printf '\n--- %s ---\n\n' "$f"
        cat "$dir/$f"
      fi
    done
  done <<<"$modules"
} >"$out"

echo "wrote $out ($(grep -c . <<<"$modules") modules)"

