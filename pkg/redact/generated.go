// tells which field managers are people and apply tools and which are controllers, so a Secret key a controller generated can be dropped outright
// a controller writes such a key again in a new cluster, so the export keeps only that it existed and who wrote it

package redact

import (
	"sort"
	"strings"

	"sigs.k8s.io/structured-merge-diff/v6/fieldpath"

	"setdrift.io/setdrift-engine/internal/kube"
	"setdrift.io/setdrift-engine/pkg/resource"
)

// the field managers of people and the tools they apply configuration with, toolManagers by exact name and toolPrefixes by how the name starts
// a Secret key written only by other field managers was generated by a controller, an operator names itself, e.g. argocd-server, external-secrets, cert-manager
var (
	toolManagers = map[string]bool{
		"helm": true, "argocd-controller": true, "kustomize-controller": true, "helm-controller": true,
		"Go-http-client": true, "OpenAPI-Generator": true, "python-requests": true, "kubernetes-dashboard": true,
		// the GitLab agent for Kubernetes (gitlab-agent internal/api FieldManager)
		"agentk": true,
		// Rancher Fleet's agent, which applies through the Helm SDK, Helm names the manager after the binary
		"fleetagent": true,
	}
	toolPrefixes = []string{"kubectl", "helm", "terraform", "Terraform", "pulumi", "kapp", "kpt", "k9s", "setdrift",
		// Crossplane provider-kubernetes Objects, named provider-kubernetes/<Object name>
		"provider-kubernetes/"}
)

// isTool takes a field manager name and tells if its a person's or an apply tool's, as opposed to a controller's
func isTool(manager string) bool {
	// checking if the name is a known tool exactly
	if toolManagers[manager] {
		return true
	}
	// checking each known prefix, a name starting with one is a tool too
	for _, p := range toolPrefixes {
		// checking if the name starts with this prefix
		if strings.HasPrefix(manager, p) {
			return true
		}
	}
	return false
}

// owners are the field managers of one Secret key, generated reads them to tell if only controllers wrote it
type owners struct {
	// the managers whose managedFields entry owns the key
	managers []string
	// set when a managedFields entry couldnt be read, so any manager, a person's included, might own the key
	unknown bool
}

// keyOwners takes a Secret and one of its fields, data or stringData, and gives back the field managers that own each key under it
func keyOwners(o *resource.Object, field string) map[string]*owners {
	out := map[string]*owners{}
	m, _ := o.Object[field].(map[string]any)
	// checking if the field is missing or empty, if so theres no key to own
	if len(m) == 0 {
		return out
	}
	// starting every key with no owners
	for k := range m {
		out[k] = &owners{}
	}
	// going through each field manager's entry to see which keys it owns
	for _, e := range o.GetManagedFields() {
		// invoking kube.FieldSet to decode the fields this entry owns, its defined in internal/kube/kube.go
		set, err := kube.FieldSet(e)
		// checking if the entry couldnt be read, if so its counted as a person's on every key, the safe side
		if err != nil {
			// marking each key as possibly owned by anyone
			for k := range m {
				out[k].unknown = true
			}
			continue
		}
		// checking if the entry records no fields, if so it owns no key
		if set == nil {
			continue
		}
		// going through the keys to see which this entry owns
		for k := range m {
			// checking if the key's path can be built and the entry owns it, if so this manager is one of its owners
			if p, err := fieldpath.MakePath(field, k); err == nil && set.Has(p) {
				out[k].managers = append(out[k].managers, e.Manager)
			}
		}
	}
	return out
}

// generated takes a key's owners and tells if theyre all controllers, and names them, comma separated and sorted
// a key with no recorded owner, like in manifests read from files, counts as a person's, so its value is replaced and not dropped as generated
func generated(o *owners) (string, bool) {
	// checking if the owners are missing, unreadable or none, if so the key counts as a person's
	if o == nil || o.unknown || len(o.managers) == 0 {
		return "", false
	}
	// checking each owner, one tool or person among them makes the key a person's
	for _, m := range o.managers {
		// invoking isTool to tell if this owner is a person or apply tool, its defined above
		if isTool(m) {
			return "", false
		}
	}
	sort.Strings(o.managers)
	return strings.Join(o.managers, ","), true
}

