// RedactedExt is the extension of the reference-only files an export writes
// under redacted/ (kustomize.RedactedExt; repeated to keep this package free
// of the emitter).
const RedactedExt = ".yaml.redacted"

// Source is one redacted Secret in an export: what to copy, from where.
type Source struct {
	Namespace, Name string
	// Keys are the Secret keys the export redacted: the ones a person or tool
	// wrote. Keys a controller generates are not in the file.
	Keys        []string
	Type        string
	Labels      map[string]string
	Annotations map[string]string
	// File is the redacted file, relative to the folder given.
	File string
}

// Folder is what a folder of redacted files holds.
type Folder struct {
	Secrets []Source
	// Others are redacted files of other kinds: resources holding secret
	// values in their manifest. They can't be copied as they are: their
	// values belong in a Secret first.
	Others []string
	// Invalid lists the files that are not what an export writes, with why.
	Invalid []string
}

// LoadRedacted reads the redacted files in dir (an export's redacted/, or a
// folder in it, such as redacted/namespaces/shop).
func LoadRedacted(dir string) (*Folder, error) {
	fi, err := os.Stat(dir)
	if err != nil {
		return nil, err
	}
	if !fi.IsDir() {
		return nil, fmt.Errorf("%s is not a directory: give the export's redacted/ folder, or a folder in it", dir)
	}
	out := &Folder{}
	err = filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		// a symlink is not followed: it could lead out of the folder
		if d.IsDir() || d.Type()&fs.ModeSymlink != 0 || !strings.HasSuffix(path, RedactedExt) {
			return nil
		}
		rel, _ := filepath.Rel(dir, path) // path is under dir: cannot fail
		rel = filepath.ToSlash(rel)
		b, err := os.ReadFile(path) //#nosec G304,G122 -- a regular file (symlinks skipped above) in the folder the user named
		if err != nil {
			return err
		}
		var m struct {
			APIVersion string `json:"apiVersion"`
			Kind       string `json:"kind"`
			Metadata   struct {
				Name        string            `json:"name"`
				Namespace   string            `json:"namespace"`
				Labels      map[string]string `json:"labels"`
				Annotations map[string]string `json:"annotations"`
			} `json:"metadata"`
			Type       string         `json:"type"`
			Data       map[string]any `json:"data"`
			StringData map[string]any `json:"stringData"`
		}
		if err := yaml.Unmarshal(b, &m); err != nil {
			out.Invalid = append(out.Invalid, rel+": not YAML: "+err.Error())
			return nil
		}
		switch {
		case m.Kind == "":
			out.Invalid = append(out.Invalid, rel+": no kind")
			return nil
		case m.APIVersion != "v1" || m.Kind != "Secret":
			out.Others = append(out.Others, rel+" ("+m.Kind+" "+m.Metadata.Namespace+"/"+m.Metadata.Name+")")
			return nil
		case m.Metadata.Name == "" || m.Metadata.Namespace == "":
			out.Invalid = append(out.Invalid, rel+": a Secret without a name and namespace")
			return nil
		}
		keys := map[string]bool{}
		for k := range m.Data {
			keys[k] = true
		}
		for k := range m.StringData {
			keys[k] = true
		}
		if len(keys) == 0 {
			// every key was generated by a controller: nothing a person wrote to copy
			return nil
		}
		s := Source{Namespace: m.Metadata.Namespace, Name: m.Metadata.Name, Type: m.Type,
			Labels: m.Metadata.Labels, Annotations: m.Metadata.Annotations, File: rel}
		for k := range keys {
			s.Keys = append(s.Keys, k)
		}
		sort.Strings(s.Keys)
		out.Secrets = append(out.Secrets, s)
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Slice(out.Secrets, func(i, j int) bool {
		if out.Secrets[i].Namespace != out.Secrets[j].Namespace {
			return out.Secrets[i].Namespace < out.Secrets[j].Namespace
		}
		return out.Secrets[i].Name < out.Secrets[j].Name
	})
	sort.Strings(out.Others)
	sort.Strings(out.Invalid)
	return out, nil
}

// Manager is a supported secret manager.
type Manager string

// The secret managers supported.
const (
	SecretsManagerID Manager = "aws-secrets-manager"
	ParameterStoreID Manager = "aws-parameter-store"
)

var (
	// Secrets Manager names: letters, digits and /_+=.@-, at most 512.
	secretsManagerName = regexp.MustCompile(`^[A-Za-z0-9/_+=.@-]+$`)
	// Parameter Store names: letters, digits and _.-/, a leading /, at most 1011.
	parameterName = regexp.MustCompile(`^/[A-Za-z0-9_./-]+$`)
)

// RemoteKeys names each Secret's remote secret with tmpl (a Go template with
// .Cluster, .Namespace and .Name) and checks every name is one the manager
// accepts and no two Secrets share one. The keys are in the order of secrets.
func RemoteKeys(m Manager, tmpl, cluster string, secrets []Source) ([]string, error) {
	t, err := template.New("key").Option("missingkey=error").Parse(tmpl)
	if err != nil {
		return nil, fmt.Errorf("--secret-key-template: %w", err)
	}
	if !strings.Contains(tmpl, ".Namespace") || !strings.Contains(tmpl, ".Name") {
		return nil, errors.New("--secret-key-template must include {{.Namespace}} and {{.Name}}, so each Secret gets a remote secret of its own")
	}
	keys := make([]string, len(secrets))
	byKey := map[string]string{}
	var bad []string
	for i, s := range secrets {
		var b bytes.Buffer
		if err := t.Execute(&b, map[string]string{"Cluster": cluster, "Namespace": s.Namespace, "Name": s.Name}); err != nil {
			return nil, fmt.Errorf("--secret-key-template: %w", err)
		}
		k := b.String()
		keys[i] = k
		if other, ok := byKey[k]; ok {
			return nil, fmt.Errorf("--secret-key-template gives %s/%s and %s the same remote secret %q", s.Namespace, s.Name, other, k)
		}
		byKey[k] = s.Namespace + "/" + s.Name
		switch m {
		case SecretsManagerID:
			if !secretsManagerName.MatchString(k) || len(k) > 512 {
				bad = append(bad, fmt.Sprintf("%q (Secrets Manager allows letters, digits and /_+=.@-, at most 512)", k))
			}
		case ParameterStoreID:
			low := strings.ToLower(k)
			if !parameterName.MatchString(k) || len(k) > 1011 || strings.HasPrefix(low, "/aws") || strings.HasPrefix(low, "/ssm") {
				bad = append(bad, fmt.Sprintf("%q (Parameter Store needs a leading /, then letters, digits and _.-/, not under /aws or /ssm)", k))
			}
		}
	}
	if len(bad) > 0 {
		return nil, fmt.Errorf("--secret-key-template makes names %s does not accept: %s", m, strings.Join(bad, "; "))
	}
	return keys, nil
}
